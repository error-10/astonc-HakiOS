"""Turn the device tree's qcom,phy-sequence into a C table.

The PCIe PHY on this board is initialised by a list of (offset, value, delay) triples that
the downstream kernel carries in the device tree, not in the driver. Replaying them is what
drivers/phy/qualcomm/phy-qcom-qmp-pcie.c does from the same list, so the data comes straight
out of Resources/DTBs/aston.dts and is only reformatted here.

    python scripts/make_phy_seq.py > port/kernel/hakios.aston_pcie_phy_seq.h
"""
import re
import sys

DT = 'repos/Mu-Silicium/Resources/DTBs/aston.dts'
OUT = sys.argv[1] if len(sys.argv) > 1 else 'port/kernel/hakios.aston_pcie_phy_seq.h'

text = open(DT, encoding='utf-8', errors='replace').read()
start = text.find('qcom,phy-sequence')
if start < 0:
    sys.exit('no qcom,phy-sequence in the device tree')
end = text.find('>', start)
numbers = [int(v, 16) for v in re.findall(r'0x[0-9a-fA-F]+', text[start:end].split('=', 1)[1])]
if len(numbers) % 3:
    sys.exit(f'the sequence is {len(numbers)} numbers, not a whole number of triples')

print('/* Generated by scripts/make_phy_seq.py from', DT, '-- do not edit by hand. */')
print('#ifndef _HAKIOS_ASTON_PCIE_PHY_SEQ_H_')
print('#define _HAKIOS_ASTON_PCIE_PHY_SEQ_H_')
print()
print('/* offset in the PHY register window, value to write, microseconds to wait afterwards */')
print('static const struct { unsigned off, value, delay_us; } aston_phy_seq[] = {')
for i in range(0, len(numbers), 3):
    off, value, delay = numbers[i:i + 3]
    print(f'\t{{ 0x{off:04x}, 0x{value:04x}, {delay} }},')
print('};')
print()
print(f'#define ASTON_PHY_SEQ_LEN {len(numbers) // 3}')
print()
print('#endif')
